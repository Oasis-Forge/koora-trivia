import '../entities/store_product.dart';

/// عقد مجرّد للشراء داخل التطبيق.
///
/// يبقى `domain` خالياً من `in_app_purchase`، فيُختبر كل المنطق بمزيّف بسيط.
///
/// **الاستحقاق مصدره المتجر لا التطبيق:** «إزالة الإعلانات» تُقرأ من مشتريات
/// اللاعب عند كل إقلاع، ويُحفظ نسخة محلية منها للعمل دون اتصال فقط. لهذا لا
/// تدخل ضمن رمز النسخ الاحتياطي: الرمز يُشارَك بين الأجهزة، فيصبح الشراء مجانياً.
abstract class BillingService {
  /// الاتصال بالمتجر، جلب المنتجات، ثم استعادة ما سبق شراؤه. تُستدعى عند الإقلاع.
  Future<void> init();

  /// يُستدعى كلما تغيّرت المنتجات أو الاستحقاق أو حالة الشراء.
  set onChanged(void Function()? listener);

  /// يُستدعى عند تسليم شراء — عند إتمامه (`restored` خطأ) أو استعادته عند
  /// الإقلاع (`restored` صحيح).
  ///
  /// التسليم قد يصل متأخراً (دفع معلّق يكتمل بعد يوم)، فلا يكفي ردّ [buy].
  /// والتمييز يمنع منح عملات الباقة ثانية عند كل استعادة.
  set onDelivered(
    void Function(StoreProductKind kind, {required bool restored})? listener,
  );

  /// هل المتجر متاح ومنتجاته معروفة؟ الشاشة تعرض «قريباً» حين لا يكون.
  bool get isAvailable;

  /// المنتجات كما وصفها المتجر، بترتيب العرض.
  List<StoreProduct> get products;

  /// هل اشترى اللاعب إزالة الإعلانات؟
  bool get adsRemoved;

  /// فتح نافذة شراء المنتج وانتظار نتيجتها.
  Future<PurchaseOutcome> buy(StoreProductKind kind);

  /// استعادة المشتريات غير المستهلَكة — يعيد عددها.
  Future<int> restore();

  void dispose();
}
