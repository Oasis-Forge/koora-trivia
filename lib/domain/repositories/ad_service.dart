/// نتيجة عرض إعلان مكافأ.
enum RewardResult {
  /// شاهد الإعلان كاملاً واستحقّ المكافأة.
  earned,

  /// أغلق الإعلان قبل اكتماله.
  dismissed,

  /// لا يوجد إعلان جاهز — غالباً انقطاع الاتصال.
  unavailable,
}

/// عقد مجرّد لطبقة الإعلانات.
///
/// يبقى `domain` خالياً من `google_mobile_ads` تماماً، فيمكن اختبار كل المنطق
/// بمزيّف بسيط دون تهيئة SDK.
abstract class AdService {
  /// طلب موافقة الخصوصية، ثم تهيئة الحزمة وتحميل الإعلانات **فقط** إن سمحت
  /// الموافقة بذلك. تُستدعى مرة عند الإقلاع.
  Future<void> init();

  /// يُستدعى كلما تغيّرت جاهزية الإعلان أو حالة الموافقة.
  ///
  /// بدونه لا تعرف الواجهة أن الإعلان اكتمل تحميله، فيبقى زره معطّلاً.
  set onChanged(void Function()? listener);

  /// يُستدعى لحظة قبل عرض إعلان بملء الشاشة (مكافأ أو بيني) فعلاً — لإيقاف
  /// مؤثرات اللعبة، فلا يُسمع الهتاف فوق صوت الإعلان.
  set beforeFullScreenAd(void Function()? callback);

  /// هل يوجد إعلان مكافأ جاهز للعرض الآن؟
  bool get isRewardedReady;

  /// هل يُسمح بعرض شريط إعلاني الآن؟ موافقة قائمة وحزمة مهيّأة وإعلانات غير
  /// مُزالة. الودجة تسأل قبل أن تحجز مكاناً أو تطلب إعلاناً.
  bool get areBannersAllowed;

  /// معرّف وحدة الشريط الإعلاني — تجريبي في التطوير وحقيقي في الإصدار.
  ///
  /// الودجة تبني الإعلان بنفسها (الودجات من `google_mobile_ads` تعيش في طبقة
  /// العرض)، فتحتاج المعرّف الذي اختارته الخدمة.
  String get bannerUnitId;

  /// هل يجب أن تعرض الإعدادات مدخلاً لتعديل موافقة الإعلانات؟
  ///
  /// غوغل تشترطه حيث تكون الموافقة مطلوبة (أوروبا مثلاً) فقط.
  bool get isPrivacyOptionsRequired;

  /// فتح نموذج خيارات الخصوصية. يعيد `false` إن تعذّر عرضه.
  Future<bool> showPrivacyOptions();

  /// عودة التطبيق إلى الواجهة — فرصة لإعادة تحميل إعلان فشل دون انتظار المهلة.
  void onAppResumed();

  /// عرض إعلان مكافأ وانتظار نتيجته.
  Future<RewardResult> showRewarded();

  /// عرض إعلان بيني إن حان دوره. يعيد `true` إن عُرض فعلاً.
  ///
  /// المنطق الداخلي يحترم سقف التكرار الزمني وعدد المستويات.
  Future<bool> maybeShowInterstitial();

  /// تسجيل انتهاء مستوى أو جولة — يُستخدم لعدّ الإعلانات البينية.
  void recordRoundFinished();

  /// هل اشترى المستخدم إزالة الإعلانات؟ يوقف البينية والشريط السفلي، ويُبقي
  /// الإعلان المكافأ لأنه اختياري ومصدر قلوب وعملات.
  set adsRemoved(bool value);
}
