/// نتيجة عرض إعلان مكافأ.
enum RewardResult {
  /// شاهد الإعلان كاملاً واستحقّ المكافأة.
  earned,

  /// أغلق الإعلان قبل اكتماله.
  dismissed,

  /// لا يوجد إعلان جاهز — غالباً انقطاع الاتصال.
  unavailable,
}

/// عقد مجرّد لطبقة الإعلانات.
///
/// يبقى `domain` خالياً من `google_mobile_ads` تماماً، فيمكن اختبار كل المنطق
/// بمزيّف بسيط دون تهيئة SDK.
abstract class AdService {
  /// تهيئة الحزمة وطلب موافقة الخصوصية. تُستدعى مرة عند الإقلاع.
  Future<void> init();

  /// هل يوجد إعلان مكافأ جاهز للعرض الآن؟
  bool get isRewardedReady;

  /// عرض إعلان مكافأ وانتظار نتيجته.
  Future<RewardResult> showRewarded();

  /// عرض إعلان بيني إن حان دوره. يعيد `true` إن عُرض فعلاً.
  ///
  /// المنطق الداخلي يحترم سقف التكرار الزمني وعدد المستويات.
  Future<bool> maybeShowInterstitial();

  /// تسجيل انتهاء مستوى أو جولة — يُستخدم لعدّ الإعلانات البينية.
  void recordRoundFinished();

  /// هل اشترى المستخدم إزالة الإعلانات؟ يوقف الإعلانات البينية فقط.
  set adsRemoved(bool value);
}
